#!/bin/bash
# track-polyfill.sh <64|32> -- make one Wine tree depend on the polyfill layer. Wine's makedep knows
# neither the header overlay nor the archive; build.sh runs this before every make of the tree.
#
# It writes the tree's GNUmakefile, which GNU make reads ahead of Makefile:
#   - every host compile (the rules taking $(CFLAGS)) also writes <object>.d, the compiler's list of
#     every header it read, system headers included (-MD -MP); make reads those lists, so an object
#     depends on the overlay headers it includes, generated ones too.
#   - every host link (the rules taking $(LDFLAGS), and so link-<arch>.rsp) depends on the rsp, the stub
#     Metal, and each archive member that defines a symbol the image names, defined or undefined: the
#     members it holds and the members that would now resolve one of its imports.
# An object compiled before the tree had a GNUmakefile gets its .d from a syntax-only pass.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/env.sh"
case "${1:-}" in
    64) ARCH=x86_64 ;;
    32) ARCH=i386 ;;
    *) echo "usage: $0 <64|32>" >&2; exit 2 ;;
esac
TREE="$WS_REPO/build/wine$1"
POLY="$WS_SUPPORT/polyfill/build"
D="$TREE/wineskin"
mkdir -p "$D/syms"
cd "$TREE"

# The host objects (with the source each compiles) and host images, from Makefile's recipes.
if [ ! -s "$D/host-objects" ] || [ Makefile -nt "$D/host-objects" ]; then
    awk -v objs="$D/host-objects.next" -v imgs="$D/host-images.next" '
        /^[^\t ]/ { hdr = $0; inrecipe = 0; next }
        /^\t/     { if (!inrecipe) { tgt = hdr; sub(/:.*/, "", tgt); src = hdr; sub(/^[^:]*: */, "", src); sub(/ .*/, "", src) }
                    inrecipe = 1 }
        inrecipe && /\$\(CFLAGS\)/  && !(tgt in o) { o[tgt]; print tgt, src > objs }
        inrecipe && /\$\(LDFLAGS\)/ && !(tgt in l) { l[tgt]; print tgt > imgs }' Makefile
    mv "$D/host-objects.next" "$D/host-objects"
    mv "$D/host-images.next" "$D/host-images"
fi

{
    echo "# Generated by WineskinSupport/scripts/track-polyfill.sh: Makefile, plus the host objects' and"
    echo "# images' dependencies on WineskinSupport/polyfill, which makedep does not see."
    echo "include Makefile"
    echo "CFLAGS += -MD -MP"
    printf -- '-include $(wildcard'
    awk '{ o = $1; sub(/\.o$/, ".d", o); printf " \\\n  %s", o }' "$D/host-objects"
    echo ")"
    echo "-include wineskin/images.mk"
} > "$D/GNUmakefile.next"
mv "$D/GNUmakefile.next" GNUmakefile

# Objects without a .d: the syntax-only pass runs each one's own compile command, its source pretended
# new (-W), with -fsyntax-only and without ccache (which would cache the untouched object as its result);
# the object itself is left as it is. An object the pass cannot reach (its source is regenerated on every
# make, which overrides -W) is deleted and compiled again.
what=() objs=()
while read -r obj src; do
    if [ -f "$obj" ] && [ ! -f "${obj%.o}.d" ]; then what+=(-W "$src"); objs+=("$obj"); fi
done < "$D/host-objects"
if [ ${#objs[@]} -gt 0 ]; then
    echo "### wine$1: header lists for ${#objs[@]} objects"
    make -j"$WS_JOBS" -O CC="$(sed -n 's/^CC = //p' Makefile | sed "s|^$WS_CCACHE ||")" \
        CFLAGS="$(sed -n 's/^CFLAGS = //p' Makefile) -fsyntax-only -MD -MP -Wno-unused-command-line-argument" \
        "${what[@]}" "${objs[@]}"
    while read -r obj src; do
        if [ -f "$obj" ] && [ ! -f "${obj%.o}.d" ]; then echo "### no header list for $obj: recompiling it"; rm -f "$obj"; fi
    done < "$D/host-objects"
fi

# The symbols each archive member defines, and those each image names. An image's list is redone when
# the image's inode, size or time changes (a relink in the second the list was made has the same time).
for m in "$POLY/obj/$ARCH"/*.o; do
    nm -gUj "$m" | sed "s|^|$m |"
done > "$D/members"
while read -r img; do
    [ -f "$img" ] || continue
    s="$D/syms/$img"
    key="#$(stat -f '%i %z %m' "$img")"
    if [ ! -f "$s" ] || [ "$(head -1 "$s")" != "$key" ]; then
        mkdir -p "$(dirname "$s")"
        { echo "$key"; nm -j "$img" | sort -u; } > "$s.next"
        mv "$s.next" "$s"
    fi
    echo "$img $s"
done < "$D/host-images" > "$D/images"
awk -v rsp="$POLY/link-$ARCH.rsp" -v metal="$POLY/Frameworks/Metal.framework/Versions/A/Metal" '
    FILENAME == ARGV[1] { if (!($1 in idx)) { idx[$1] = ++nm; member[nm] = $1 }
                          def[$2] = def[$2] " " idx[$1]; next }
    FILENAME == ARGV[2] { img[$2] = $1; order[++ni] = $2; next }
    ($1 in def) { c = split(def[$1], ms, " "); for (i = 1; i <= c; i++) uses[FILENAME, ms[i]] = 1 }
    END {
        print "# Generated by WineskinSupport/scripts/track-polyfill.sh: each host image depends on the"
        print "# polyfill files its link reads."
        for (k = 1; k <= ni; k++) {
            f = order[k]; line = img[f] ": " rsp " " metal
            for (j = 1; j <= nm; j++) if ((f, j) in uses) line = line " \\\n  " member[j]
            print line
        }
        # Empty rules: a file that goes away is no error before this file is rewritten.
        print rsp ":"; print metal ":"
        for (j = 1; j <= nm; j++) print member[j] ":"
    }' "$D/members" "$D/images" $(awk '{ print $2 }' "$D/images") > "$D/images.mk.next"
mv "$D/images.mk.next" "$D/images.mk"
